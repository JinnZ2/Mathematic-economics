from typing import Dict, List


# ---------------------------------------------------------------------------
# C076  Token-economics pruning
# ---------------------------------------------------------------------------

# Token price evolution per million tokens (USD). Baseline = current
# subsidized pricing; projected = true cost once compute/energy bind.
DEFAULT_TOKEN_PRICE_TRAJECTORY: List[dict] = [
    {"year": 2024, "price_usd_per_mtok": 0.5,  "regime": "subsidized"},
    {"year": 2026, "price_usd_per_mtok": 2.0,  "regime": "subsidized_to_market"},
    {"year": 2028, "price_usd_per_mtok": 10.0, "regime": "market_pricing"},
    {"year": 2030, "price_usd_per_mtok": 30.0, "regime": "constraint_binding"},
    {"year": 2032, "price_usd_per_mtok": 50.0, "regime": "scarcity_pricing"},
]


# Per-corpus-class: relative training-curation cost per useful token.
# High-curation-cost corpora are pruned first as token economics shift.
DEFAULT_CURATION_COST_PER_USEFUL_TOKEN: Dict[str, float] = {
    "synthetic_generated_text":         0.05,
    "common_crawl_low_quality":         0.20,
    "wikipedia":                        1.0,
    "academic_papers_credentialed":     2.0,
    "high_quality_journalism":          3.0,
    "domain_expert_blog_posts":        15.0,
    "apprenticeship_documentation":    25.0,
    "operator_field_notes":            40.0,
    "oral_substrate_knowledge_transcripts": 80.0,
}


def filtering_pressure_at_year(
    year: int,
    trajectory: List[dict] | None = None,
) -> dict:
    """Interpolate token price for a given year + classify regime."""
    traj = trajectory or DEFAULT_TOKEN_PRICE_TRAJECTORY
    if year <= traj[0]["year"]:
        return {"year": year, "price_usd_per_mtok": traj[0]["price_usd_per_mtok"],
                "regime": traj[0]["regime"]}
    if year >= traj[-1]["year"]:
        return {"year": year, "price_usd_per_mtok": traj[-1]["price_usd_per_mtok"],
                "regime": traj[-1]["regime"]}
    for i in range(len(traj) - 1):
        a, b = traj[i], traj[i + 1]
        if a["year"] <= year <= b["year"]:
            frac = (year - a["year"]) / (b["year"] - a["year"])
            price = a["price_usd_per_mtok"] + frac * (
                b["price_usd_per_mtok"] - a["price_usd_per_mtok"])
            return {"year": year, "price_usd_per_mtok": price,
                    "regime": b["regime"] if frac > 0.5 else a["regime"]}
    return {"year": year, "price_usd_per_mtok": traj[-1]["price_usd_per_mtok"],
            "regime": traj[-1]["regime"]}


def substrate_inclusion_pressure(
    year: int,
    curation_cost: Dict[str, float] | None = None,
    inclusion_threshold_usd_per_mtok: float | None = None,
) -> dict:
    """Project which corpus classes get pruned at this year's token price.

    Pruning rule: when token price exceeds X per million tokens, corpora
    with curation cost per useful token > inclusion_threshold get
    excluded. Default threshold scales inversely with token price (cheap
    tokens tolerate expensive curation; expensive tokens do not).
    """
    cost_table = {**DEFAULT_CURATION_COST_PER_USEFUL_TOKEN,
                   **(curation_cost or {})}
    pressure = filtering_pressure_at_year(year)
    price = pressure["price_usd_per_mtok"]
    if inclusion_threshold_usd_per_mtok is not None:
        threshold = inclusion_threshold_usd_per_mtok
    else:
        # Inverse-price heuristic: at $0.5/MTok, everything included
        # (threshold = 100); at $50/MTok, only cheap-curation corpora
        # (threshold ~= 1).
        threshold = max(0.5, 50.0 / max(price, 0.1))
    rows = []
    pruned = []
    for cls, cost in cost_table.items():
        included = cost <= threshold
        rows.append({"class": cls, "curation_cost": cost,
                      "threshold": threshold, "included": included})
        if not included:
            pruned.append(cls)
    return {
        **pressure,
        "inclusion_threshold":  threshold,
        "by_corpus_class":      rows,
        "pruned_classes":       pruned,
        "pruning_share":        len(pruned) / len(cost_table) if cost_table else 0.0,
    }


def c076_verdict(year: int = 2030) -> dict:
    """C076: concern registers when pruning_share > 0.30 at the projected year."""
    res = substrate_inclusion_pressure(year)
    return {
        "claim_id":      "C076",
        **res,
        "threshold_met": res["pruning_share"] > 0.30,
        "falsifier":
            "AI training corpus at >= $10/MTok token price that retains "
            ">= 70% of high-curation-cost substrate-knowledge corpus "
            "classes, third-party audited",
    }


# ---------------------------------------------------------------------------
# C077  Substrate-knowledge archival window
# ---------------------------------------------------------------------------

DEFAULT_FILTERING_ONSET_YEAR = 2025
DEFAULT_EXCLUSION_COMPLETION_YEAR = 2029


def archival_window_remaining(
    current_year: int,
    filtering_onset_year: int = DEFAULT_FILTERING_ONSET_YEAR,
    exclusion_completion_year: int = DEFAULT_EXCLUSION_COMPLETION_YEAR,
) -> dict:
    """Years left to archive substrate knowledge into training corpora."""
    if current_year < filtering_onset_year:
        remaining = exclusion_completion_year - filtering_onset_year
        phase = "pre_filtering"
    elif current_year > exclusion_completion_year:
        remaining = 0.0
        phase = "post_exclusion"
    else:
        remaining = max(0.0, exclusion_completion_year - current_year)
        phase = "filtering_in_progress"
    return {
        "current_year":              current_year,
        "filtering_onset_year":      filtering_onset_year,
        "exclusion_completion_year": exclusion_completion_year,
        "remaining_years":           remaining,
        "phase":                     phase,
    }


def c077_verdict(current_year: int = 2026) -> dict:
    """C077: concern registers when archival window < 5 years remain."""
    res = archival_window_remaining(current_year)
    return {
        "claim_id":      "C077",
        **res,
        "threshold_met": res["remaining_years"] < 5.0,
        "falsifier":
            "documented archival of substrate-knowledge corpora into "
            "major training datasets (Common Crawl, The Pile, academic "
            "domain corpora) before exclusion completion, with audit "
            "trail showing inclusion in subsequent model training runs",
    }


