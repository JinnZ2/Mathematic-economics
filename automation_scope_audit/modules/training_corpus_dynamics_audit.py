CASCADE_STEPS = [
    {"step": 1, "name": "credential_inversion",       "claim": "C065",
     "marker": "credentialed non-experts override substrate experts"},
    {"step": 2, "name": "blame_deflection",           "claim": "C069",
     "marker": "failures attributed to AI / data / compute, not to decision authority"},
    {"step": 3, "name": "training_data_bias",         "claim": "C067",
     "marker": "AI corpus skewed > 80% to credentialed sources"},
    {"step": 4, "name": "token_economics_filtering",  "claim": "C076",
     "marker": "rising token price prunes high-curation-cost corpora"},
    {"step": 5, "name": "recursive_homogenization",   "claim": "C078",
     "marker": "synthetic-content share > 50% in training corpus"},
    {"step": 6, "name": "confidence_inflation",       "claim": None,
     "marker": "model confidence rises while substrate accuracy falls"},
    {"step": 7, "name": "precondition_check_elimination", "claim": "C000",
     "marker": "scope gates and precondition checks dismissed as overhead"},
    {"step": 8, "name": "system_collapse",            "claim": "C068",
     "marker": "substrate degradation becomes visible at catastrophic failure"},
]


def cascade_step_match(
    step_name: str,
    report: Dict[str, dict],
) -> dict:
    """Check whether a given cascade step's marker is present in an audit report."""
    step = next((s for s in CASCADE_STEPS if s["name"] == step_name), None)
    if step is None:
        return {"step_name": step_name, "matches": False, "reason": "unknown step"}
    if not step["claim"]:
        return {"step_name": step_name, "matches": None,
                "reason": "no claim-level marker; manual observation required"}
    verdict = report.get(step["claim"]) or {}
    matches = bool(verdict.get("threshold_met"))
    return {"step_name": step_name, "claim": step["claim"],
             "matches": matches, "marker": step["marker"]}


def cascade_trajectory_match(report: Dict[str, dict]) -> dict:
    """Run all 8 cascade steps against an audit report."""
    rows = [cascade_step_match(s["name"], report) for s in CASCADE_STEPS]
    matched = sum(1 for r in rows if r.get("matches"))
    unknown = sum(1 for r in rows if r.get("matches") is None)
    total = len(rows)
    return {
        "by_step":        rows,
        "matched_steps":  matched,
        "unknown_steps":  unknown,
        "total_steps":    total,
        "matched_share":  matched / max(1, total - unknown),
    }


def c079_verdict(report: Dict[str, dict] | None = None) -> dict:
    """C079: concern registers when >= 5/7 claim-level cascade steps match."""
    if report is None:
        # Self-test fallback: assume all observable steps register
        rows = [{"step_name": s["name"], "claim": s["claim"],
                  "matches": True if s["claim"] else None,
                  "marker": s["marker"]}
                for s in CASCADE_STEPS]
        matched = sum(1 for r in rows if r["matches"] is True)
        total_observable = sum(1 for r in rows if r["matches"] is not None)
        res = {
            "by_step":       rows,
            "matched_steps": matched,
            "unknown_steps": len(rows) - total_observable,
            "total_steps":   len(rows),
            "matched_share": matched / max(1, total_observable),
        }
    else:
        res = cascade_trajectory_match(report)
    return {
        "claim_id":      "C079",
        **res,
        "cascade_steps": CASCADE_STEPS,
        "threshold_met": res["matched_steps"] >= 5,
        "falsifier":
            "deployment cohort traversing the 4-phase adoption curve "
            "without matching 5+ of the 8-step cascade markers, "
            "audited over a full obsolescence-transition cycle",
    }


