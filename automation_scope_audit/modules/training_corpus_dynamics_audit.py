DEFAULT_SYNTHETIC_SHARE_TRAJECTORY: List[dict] = [
    {"year": 2022, "synthetic_share": 0.005},
    {"year": 2024, "synthetic_share": 0.05},
    {"year": 2026, "synthetic_share": 0.20},
    {"year": 2028, "synthetic_share": 0.45},
    {"year": 2030, "synthetic_share": 0.70},
    {"year": 2032, "synthetic_share": 0.85},
]


def synthetic_content_share_at_year(
    year: int,
    trajectory: List[dict] | None = None,
) -> float:
    """Linear interpolation across the synthetic-share trajectory."""
    traj = trajectory or DEFAULT_SYNTHETIC_SHARE_TRAJECTORY
    if year <= traj[0]["year"]:
        return traj[0]["synthetic_share"]
    if year >= traj[-1]["year"]:
        return traj[-1]["synthetic_share"]
    for i in range(len(traj) - 1):
        a, b = traj[i], traj[i + 1]
        if a["year"] <= year <= b["year"]:
            frac = (year - a["year"]) / (b["year"] - a["year"])
            return a["synthetic_share"] + frac * (
                b["synthetic_share"] - a["synthetic_share"])
    return traj[-1]["synthetic_share"]


def homogenization_score(
    synthetic_share: float,
    substrate_share: float,
) -> dict:
    """Recursive homogenization concern.

    Triggers when synthetic content dominates AND substrate knowledge
    is near zero. The combination is what produces high-confidence /
    low-diversity / wrong-but-coherent output.
    """
    return {
        "synthetic_share":          synthetic_share,
        "substrate_share":          substrate_share,
        "diversity_index":          max(0.0, 1.0 - synthetic_share),
        "high_confidence_low_diversity": synthetic_share > 0.50
                                          and substrate_share < 0.05,
    }


def c078_verdict(year: int = 2030,
                 substrate_share: float = 0.02) -> dict:
    """C078: concern registers under high synthetic share + low substrate share."""
    syn = synthetic_content_share_at_year(year)
    res = homogenization_score(syn, substrate_share)
    return {
        "claim_id":      "C078",
        "year":          year,
        **res,
        "threshold_met": res["high_confidence_low_diversity"],
        "falsifier":
            "model trained at >= 50% synthetic content share AND retaining "
            ">= 5% substrate-knowledge content, with audited diversity / "
            "accuracy comparable to pre-synthetic-dominance baselines",
    }


