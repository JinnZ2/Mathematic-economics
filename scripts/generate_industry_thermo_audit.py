def generate(industry: str, output_dir: str = ".", dry_run: bool = False):
    if industry not in INDUSTRY_SPECS:
        print(f"Unknown industry: {industry}")
        return
    spec = INDUSTRY_SPECS[industry]
    date_str = datetime.now().strftime("%Y-%m-%d")

    # Build cost fields for dataclass
    cost_fields = "\n    ".join(f"{name}: float = 0.0" for name in spec["cost_categories"])
    baseline_fields = "\n    ".join(f"{name}: float = 0.0" for name in spec["cost_categories"])
    supply_entries = "\n    ".join(
        f'SupplyConstraint(item="{c[0]}", available={c[1]}, lead_time_weeks={c[2]}, sourcing_risk="{c[3]}"),'
        for c in spec["supply_constraints"]
    )
    study_fields = "\n    ".join(f"{k}: float = {v}" if isinstance(v, (int, float)) else f'{k}: str = "{v}"'
                                 for k, v in spec["example_study"].items())
    example_citation = spec["example_study"].get("citation", "Example study")

    file_content = TEMPLATE.format(
        industry=industry,
        description=spec["description"],
        date=date_str,
        cost_fields=cost_fields,
        baseline_fields=baseline_fields,
        supply_entries=supply_entries,
        example_citation=example_citation,
        study_fields=study_fields,
    )

    filename = f"{industry}_thermo_audit.py"
    filepath = os.path.join(output_dir, filename)
    if dry_run:
        print("=== DRY RUN ===")
        print(file_content)
        print("=== END ===")
    else:
        with open(filepath, "w") as f:
            f.write(file_content)
        print(f"Generated {filepath}")

def main():
    parser = argparse.ArgumentParser(description="Generate industry thermodynamic audit modules.")
    parser.add_argument("--industry", choices=list(INDUSTRY_SPECS.keys()) + ["all"], default="all")
    parser.add_argument("--output-dir", default=".")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if args.industry == "all":
        for ind in INDUSTRY_SPECS:
            generate(ind, args.output_dir, args.dry_run)
    else:
        generate(args.industry, args.output_dir, args.dry_run)

if __name__ == "__main__":
    main()
